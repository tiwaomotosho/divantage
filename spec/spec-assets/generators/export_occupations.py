"""Export the exhaustive occupations directory (all identities) as CSV and Markdown.
Usage: python3 -I export_occupations.py <pack_dir>"""
import json, os, sys, csv, collections
B = sys.argv[1]; T = os.path.join(B, "spec-assets/taxonomy/identities")
L = lambda f: json.load(open(os.path.join(T, f), encoding="utf-8"))["values"]
ids, fams, secs = L("identities.json"), {f["slug"]: f for f in L("families.json")}, {s["slug"]: s for s in L("sectors.json")}
units = {u["code"]: u["title"] if "title" in u else u.get("label", "") for u in L("isco08-unit-groups.json")}
by = {i["slug"]: i for i in ids}
out = os.path.join(B, "08_Starter_Catalogue/occupations"); os.makedirs(out, exist_ok=True)
rows = sorted(ids, key=lambda i: (secs[i["sector"]]["label"], fams[i["family"]]["label"], i["label"]))
with open(os.path.join(out, "occupations-directory.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["label", "slug", "kind", "parent", "sector", "family", "isco08_submajor", "isco08_unit_groups", "aliases"])
    for i in rows:
        w.writerow([i["label"], i["slug"], i["kind"], by[i["parent"]]["label"] if i.get("parent") else "", secs[i["sector"]]["label"], fams[i["family"]]["label"],
                    i.get("isco08_submajor", ""), " ".join(i.get("isco08_units", [])), "; ".join(i.get("aliases", []))])
md = ["# Occupations and life-role directory", "", f"Every identity a person can choose on the landing question “Who are you?”: **{len(ids):,} identities** "
      f"({sum(1 for i in ids if i['kind']=='profession'):,} professions, {sum(1 for i in ids if i['kind']=='specialism'):,} specialisms, {sum(1 for i in ids if i['kind']=='life_role'):,} life roles), "
      f"**{sum(len(i.get('aliases', [])) for i in ids):,} aliases**, in {len(secs)} sectors and {len(fams)} families. "
      "All 436 ISCO-08 unit groups are covered. Generated by `spec-assets/generators/export_occupations.py`; do not edit by hand.", ""]
g = collections.defaultdict(lambda: collections.defaultdict(list))
for i in rows: g[secs[i["sector"]]["label"]][fams[i["family"]]["label"]].append(i)
for s, fs in g.items():
    md += [f"## {s}", ""]
    for fl, items in fs.items():
        md.append(f"**{fl}** ({len(items)}): " + ", ".join(i["label"] + (f" ({', '.join(i['aliases'][:3])})" if i.get("aliases") else "") for i in items))
        md.append("")
open(os.path.join(out, "occupations-directory.md"), "w", encoding="utf-8").write("\n".join(md))
print(f"occupations directory: {len(ids)} identities -> 08_Starter_Catalogue/occupations/")
