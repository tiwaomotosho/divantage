#!/usr/bin/env python3
"""Write the feature matrix table into doc 23 between the BEGIN/END markers. Usage: python3 -I export_feature_matrix.py <pack-root>"""
import csv, os, sys
root = sys.argv[1]
rows = list(csv.DictReader(open(os.path.join(root, "spec-assets/qa/feature-matrix.csv"), encoding="utf-8")))
def cell(s): return s.replace("|", "/").strip() or "–"
lines = ["| ID | What you asked for | What the app does | Decisions | Requirements | Screens | Tests | Stage | Flags |", "|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    lines.append("| " + " | ".join([r["feature_id"], r["owner_words"], r["feature"] + (f" *({r['status_note']})*" if r["status_note"] else "")] + [cell(r[k]) for k in ("decisions", "requirements", "screens", "tests")] + [r["stage"], cell(r["flags"])]) + " |")
table = "\n".join(lines)
p = os.path.join(root, "23_Feature_Completeness_and_App_Scope.md"); s = open(p, encoding="utf-8").read()
a, b = "<!-- BEGIN MATRIX (generated by export_feature_matrix.py; edit spec-assets/qa/feature-matrix.csv) -->", "<!-- END MATRIX -->"
i, j = s.index(a) + len(a), s.index(b)
open(p, "w", encoding="utf-8").write(s[:i] + "\n" + table + "\n" + s[j:])
print(f"feature matrix: {len(rows)} rows written")
