def crop_ratio(im, r, fx, fy):
    W, H = im.size; tr = r[0] / r[1]
    if W / H > tr: w, h = int(H * tr), H
    else: w, h = W, int(W / tr)
    x = min(max(int(fx * W - w / 2), 0), W - w); y = min(max(int(fy * H - h / 2), 0), H - h)
    return im.crop((x, y, x + w, y + h))

