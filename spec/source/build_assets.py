def mono_svg(name, hue, mode='light'):
    import re as _re
    name = _re.sub(r'\s*\(.*?\)', '', name).strip() or name
    ws = name.replace(':', ' ').replace('.', ' ').replace('-', ' ').split()
    ini = (ws[0][0] + ws[1][0]).upper() if len(ws) > 1 else (ws[0][:2].capitalize() if ws[0][1:2].islower() else ws[0][:2])
    ini = ini.replace('&', '').replace('<', '')[:2] or '?'
    fg = HUE[hue]['light'][1]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="{name}">'
            f'<rect width="64" height="64" rx="16" fill="{fg}"/>'
            f'<text x="32" y="41" text-anchor="middle" font-family="Schibsted Grotesk, Inter, system-ui, sans-serif" font-weight="800" font-size="24" letter-spacing="-0.5" fill="#FFFFFF">{ini}</text></svg>\n')

